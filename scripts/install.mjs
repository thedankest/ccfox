#!/usr/bin/env node
// Registers the ccfox native messaging host with Zen and Firefox, and builds
// dist/ccfox.xpi. Safe to re-run. `--uninstall` removes the registrations.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HOST_NAME = "ccfox";
// The permanent add-on ID (the one on addons.mozilla.org), plus earlier IDs so installs
// of older builds keep connecting until they update.
const EXT_ID = "ccfox@thedankest";
const LEGACY_EXT_IDS = ["ccfox@local"];
const home = os.homedir();

const manifestDirs =
  process.platform === "darwin"
    ? [
        path.join(home, "Library/Application Support/zen/NativeMessagingHosts"),
        path.join(home, "Library/Application Support/Mozilla/NativeMessagingHosts"),
      ]
    : process.platform === "linux"
      ? [path.join(home, ".zen/native-messaging-hosts"), path.join(home, ".mozilla/native-messaging-hosts")]
      : null;

if (!manifestDirs) {
  console.error("Only macOS and Linux are supported by this installer (Windows needs a registry key).");
  process.exit(1);
}

if (process.argv.includes("--uninstall")) {
  for (const d of manifestDirs) {
    const f = path.join(d, `${HOST_NAME}.json`);
    if (fs.existsSync(f)) {
      fs.unlinkSync(f);
      console.log(`removed ${f}`);
    }
  }
  process.exit(0);
}

// 1. Copy the runtime (host, MCP server, shared tool definitions) out of the repo
//    and install its production dependencies there. The copy matters on macOS:
//    Firefox spawns hosts "disclaimed" (responsible for themselves), and such
//    processes, and the `claude` processes they start, may not read TCC-protected
//    folders like ~/Documents, ~/Desktop or ~/Downloads, so a host living in the repo
//    dies before running a line. The host imports the Claude Agent SDK, so it lives
//    next to node_modules in ~/.ccfox/app. Optional dependencies are omitted: those
//    are the SDK's bundled Claude Code binaries, and ccfox runs the user's own `claude`.
const zcHome = process.env.CCFOX_HOME || path.join(home, ".ccfox");
const appDir = path.join(zcHome, "app");
for (const dir of ["host", "server"]) fs.mkdirSync(path.join(appDir, dir), { recursive: true });
for (const f of ["host/native-host.mjs", "server/mcp-server.mjs", "server/tools.mjs", "package.json", "package-lock.json"]) {
  fs.copyFileSync(path.join(ROOT, f), path.join(appDir, f));
}
// The fox icon the MCP servers report in their serverInfo.
fs.copyFileSync(path.join(ROOT, "docs/icon.png"), path.join(appDir, "server/icon.png"));
execFileSync("npm", ["ci", "--omit=dev", "--omit=optional", "--no-audit", "--no-fund", "--loglevel=error"], { cwd: appDir, stdio: "inherit" });
console.log(`runtime    ${appDir}`);

// 2. A launcher with an absolute node path (browsers start hosts with a minimal PATH).
const binDir = path.join(zcHome, "bin");
fs.mkdirSync(binDir, { recursive: true, mode: 0o700 });
const hostScript = path.join(appDir, "host", "native-host.mjs");
fs.rmSync(path.join(binDir, "native-host.mjs"), { force: true }); // pre-0.4 location
const launcher = path.join(binDir, "ccfox-host");
fs.writeFileSync(launcher, `#!/bin/sh\n# Generated by ccfox scripts/install.mjs — re-run it after changing host/ or server/\nexec "${process.execPath}" "${hostScript}" "$@"\n`);
fs.chmodSync(launcher, 0o755);
console.log(`host       ${launcher}`);

function which(cmd) {
  for (const dir of (process.env.PATH || "").split(path.delimiter)) {
    const p = path.join(dir, cmd);
    try {
      fs.accessSync(p, fs.constants.X_OK);
      return p;
    } catch {}
  }
  return null;
}
const claudePath = which("claude") || [path.join(home, ".local/bin/claude"), path.join(home, ".claude/local/claude"), "/opt/homebrew/bin/claude", "/usr/local/bin/claude"].find((p) => fs.existsSync(p)) || null;
fs.writeFileSync(
  path.join(zcHome, "config.json"),
  JSON.stringify({ node: process.execPath, claude: claudePath, server: path.join(appDir, "server", "mcp-server.mjs") }, null, 2) + "\n",
);
console.log(`claude     ${claudePath || "NOT FOUND — install Claude Code for the side panel, then re-run this"}`);

// 3. Native messaging manifests (and removal of the pre-rename "zenclaude" ones).
for (const d of manifestDirs) {
  const legacy = path.join(d, "zenclaude.json");
  if (fs.existsSync(legacy)) {
    fs.unlinkSync(legacy);
    console.log(`removed    ${legacy} (old name)`);
  }
}
const manifest = {
  name: HOST_NAME,
  description: "ccfox: side-panel chats and Claude Code browser control",
  path: launcher,
  type: "stdio",
  allowed_extensions: [EXT_ID, ...LEGACY_EXT_IDS],
};
for (const d of manifestDirs) {
  fs.mkdirSync(d, { recursive: true });
  const f = path.join(d, `${HOST_NAME}.json`);
  fs.writeFileSync(f, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`manifest   ${f}`);
}

// 4. Package the extension.
const dist = path.join(ROOT, "dist");
fs.mkdirSync(dist, { recursive: true });
const xpi = path.join(dist, "ccfox.xpi");
if (fs.existsSync(xpi)) fs.unlinkSync(xpi);
execFileSync("zip", ["-r", "-q", "-X", xpi, ".", "-x", ".*", "-x", "*/.*"], { cwd: path.join(ROOT, "extension") });
console.log(`extension  ${xpi}`);

// Register the installed copy: it survives moving or deleting this folder.
const server = path.join(appDir, "server", "mcp-server.mjs");
console.log(`
Done. Next:
  1. In Zen, open about:config and set xpinstall.signatures.required = false
     (Zen allows unsigned add-ons once this is off), then open about:addons,
     click the gear icon > "Install Add-on From File…" and pick:
       ${xpi}
     The toolbar button (or Alt+Shift+C) opens the Claude side panel.
     This is the developer build (it includes javascript_exec). Since 0.7.0 the add-on
     ID is ${EXT_ID}; a copy installed before that (${LEGACY_EXT_IDS.join(", ")}) is a separate
     add-on, so remove it from about:addons.
  2. Register the MCP server so Claude Code can drive Zen too:
       claude mcp add --scope user ccfox -- "${process.execPath}" "${server}"
`);
