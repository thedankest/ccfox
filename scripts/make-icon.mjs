// Builds extension/icons/icon.svg and the PNG icons (icon-48/96/128.png) from the pixel
// map below (crisp pixel-art fox). The PNGs scale each fox pixel by a whole number
// (nearest neighbour), so edges stay sharp at every size.
import fs from "node:fs";
import zlib from "node:zlib";
const map = `
.O...........O.....
.OO.........OO.....
.OdO.......OdO.....
.OdOO.....OOdO..WW.
.OOOOOOOOOOOOO.TTW.
OOOOOOOOOOOOOOOTT..
OOOKOOOOOOOKOOOTT..
OOOKOOOOOOOKOOTT...
OOOWWWOKOWWWOOT....
OOOOWWWWWWWOOOT....
.OOOOWWWWWOOOO.....
.OO.OO...OO.OO.....
.OO.OO...OO.OO.....`.trim().split("\n");
const colors = { O: "#E8682A", d: "#8A3412", K: "#1F1410", W: "#FFF1E2", T: "#E8682A" };
const w = Math.max(...map.map((r) => r.length)), h = map.length;
const pad = 1, size = Math.max(w, h) + pad * 2;
const ox = (size - w) / 2, oy = (size - h) / 2;
let rects = "";
map.forEach((row, y) => [...row].forEach((c, x) => {
  if (colors[c]) rects += `<rect x="${x + ox}" y="${y + oy}" width="1.02" height="1.02" fill="${colors[c]}"/>`;
}));
fs.writeFileSync(new URL("../extension/icons/icon.svg", import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges"><!-- ccfox: pixel fox (generated by scripts/make-icon.mjs) -->${rects}</svg>\n`);
console.log(`icon ${w}x${h} in ${size}x${size}`);

// ---------------------------------------------------------------- PNG icons
const CRC = new Int32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c;
});
const crc32 = (buf) => {
  let c = -1;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
};
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function png(px, scale) {
  const fw = w * scale, fh = h * scale;
  const x0 = Math.floor((px - fw) / 2), y0 = Math.floor((px - fh) / 2);
  const rows = [];
  for (let y = 0; y < px; y++) {
    const row = Buffer.alloc(1 + px * 4); // filter byte 0, then RGBA
    for (let x = 0; x < px; x++) {
      const mx = Math.floor((x - x0) / scale), my = Math.floor((y - y0) / scale);
      const c = x >= x0 && y >= y0 && my < h && mx < w ? colors[map[my][mx]] : null;
      if (!c) continue;
      const i = 1 + x * 4;
      row[i] = parseInt(c.slice(1, 3), 16);
      row[i + 1] = parseInt(c.slice(3, 5), 16);
      row[i + 2] = parseInt(c.slice(5, 7), 16);
      row[i + 3] = 255;
    }
    rows.push(row);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(px, 0);
  ihdr.writeUInt32BE(px, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(Buffer.concat(rows), { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
// size -> whole-number scale per fox pixel (19x13 fox: 38, 76 and 114 px wide)
for (const [px, scale] of [[48, 2], [96, 4], [128, 6]]) {
  fs.writeFileSync(new URL(`../extension/icons/icon-${px}.png`, import.meta.url), png(px, scale));
  console.log(`icon-${px}.png: fox ${w * scale}x${h * scale}`);
}
